/** Regenerate the Petaluma clef and staff icon: node scripts/lead-sheet-icon.ts */
import { writeFileSync } from 'node:fs'
import { VerovioToolkit } from 'verovio/esm'
import createModule from 'verovio/wasm'

// Verovio's wrapper methods are created dynamically and are absent from its declarations.
const toolkit = new VerovioToolkit(await createModule()) as {
  setOptions(options: Record<string, unknown>): void
  loadData(mei: string): boolean
  renderToSVG(page: number): string
}
toolkit.setOptions({
  font: 'Petaluma',
  handwrittenFont: ['Petaluma'],
  svgRemoveXlink: true,
  header: 'none',
  footer: 'none',
})
toolkit.loadData(`<mei xmlns="http://www.music-encoding.org/ns/mei" meiversion="5.0">
  <meiHead><fileDesc><titleStmt><title>Lead sheet icon</title></titleStmt><pubStmt/></fileDesc></meiHead>
  <music><body><mdiv><score>
    <scoreDef><staffGrp><staffDef n="1" lines="5" clef.shape="G" clef.line="2"/></staffGrp></scoreDef>
    <section><measure><staff n="1"><layer n="1"><mSpace/></layer></staff></measure></section>
  </score></mdiv></body></music>
</mei>`)
const svg = toolkit.renderToSVG(1)
const glyph = svg.match(/<path transform="scale\(1,-1\)" d="([^"]+)"/)
const clef = svg.match(/<use href="#E050-[^"]+" transform="([^"]+)"/)
const staff = [...svg.matchAll(/<path d="M0 (\d+) L\d+ \1" stroke-width="([^"]+)"/g)]
if (!glyph || !clef || staff.length !== 5) throw new Error('Unexpected Verovio clef or staff')

// Crop the empty staff to a square around its clef; keep the engraved vertical positions and weights.
// Inline the glyph instead of using generated ids, since several buttons can share a page.
const lines = staff
  .map(([, y, width]) => `<path d="M0 ${y}H1200" stroke-width="${width}" />`)
  .join('')
const icon = `<g transform="translate(2,-3) scale(0.0166666667)" stroke="none"><g stroke="currentColor" stroke-linecap="butt">${lines}</g><g fill="currentColor" transform="${clef[1]}"><path transform="scale(1,-1)" d="${glyph[1]}" /></g></g>`
writeFileSync(
  new URL('../src/js/lead-sheet-icon.ts', import.meta.url),
  `/** Generated by node scripts/lead-sheet-icon.ts using Verovio's Petaluma font (SIL OFL 1.1). */\nexport const leadSheetIcon =\n  '${icon}'\n`
)
